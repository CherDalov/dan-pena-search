/**
 * One thing to look for inside a theme. The rules are applied by the search
 * API (api/_theme.js) and were checked against the real transcripts with
 * scripts/check_themes.mjs, including caption misspellings (e.g. "IBIDA").
 */
export interface LookFor {
  id: string;
  label: string;
  hint: string;
  /** phrases looked up in the index (stemmed: "negotiate" finds "negotiating") */
  search: string[];
  /** one must be in the moment itself, as whole words ("*" = any ending); highlighted */
  words: string[];
  /** phrases that don't count because they mean something else */
  ignore?: string[];
  /** topic words: one must be in the moment or the ones right before or after it */
  near?: string[];
}

export interface Theme {
  id: string;
  title: string;
  blurb: string;
  icon: LucideIcon;
  items: LookFor[];
}

export interface ThemeGroup {
  title: string;
  themes: Theme[];
}

const slug = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function theme(
  id: string,
  title: string,
  blurb: string,
  icon: LucideIcon,
  items: Omit<LookFor, "id">[]
): Theme {
  return { id, title, blurb, icon, items: items.map((it) => ({ ...it, id: slug(it.label) })) };
}

